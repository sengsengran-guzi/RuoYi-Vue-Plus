-- ----------------------------------------------------------------
-- GZ-JP-301 发货上报：把「需要人工介入」的事实从 last_error 里搬出来
--
-- last_error 的语义是「最近一次上报失败的原因」，每次上报回写都会覆写它（成功时置 NULL）。
-- 但代码里有两处往它写的是**完全不同性质**的东西 —— 需要 owner 人工处理的既成事实：
--   ① 包裹数已达微信上限 15，第 16/17 个运单**永远并不进上报清单**，需人工并单；
--   ② 入队失败，本次运单没能并进清单。
-- 这两条一旦被下一次成功上报清空，admin 发货管理页看到的就是一行干干净净的 success，
-- 而那 2 个运单号从没进过微信 —— 零痕迹。实测：17 个包裹发完后 last_error=NULL。
--
-- 所以另开一列存它，只由「人工处理完」显式清除，上报结果一律不碰。
-- ----------------------------------------------------------------
ALTER TABLE gz_pay_shipping_order
    ADD COLUMN manual_note VARCHAR(500) NULL
        COMMENT '需人工介入的事实（超 15 包裹上限被丢弃的运单 / 入队失败未并入的运单）。上报结果不覆写，只由人工处理后清除'
        AFTER last_error;
