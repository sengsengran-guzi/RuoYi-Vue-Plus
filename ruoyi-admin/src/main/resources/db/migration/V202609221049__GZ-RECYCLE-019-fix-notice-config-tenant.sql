-- GZ-RECYCLE-019 补丁 — 修正回收到店注意事项 sys_config 行的 tenant_id
--
-- 根因（与 V202608271157 修客服二维码完全同一个坑）：V202609211414 裸 INSERT 没写 tenant_id，
--   落到 sys_config.tenant_id 列默认值 '000000'；而项目已合并为单租户 1001（V202607272010）。
-- 后果：
--   1) 小程序登录用户的请求带 tenant=1001 → 查不到这一行 → 注意事项整块不显示
--      （匿名请求没有租户上下文、不做过滤，所以匿名能看到 —— 本地自测、开发者工具游客态都「正常」，
--       体验版登录用户看不到，2026-09-22 甲方反馈）；
--   2) admin「参数设置」按当前租户 1001 查询，甲方搜不到这一行，改不了文案。
--
-- ⚠️ 仅改库不够：ruoyi 会把 1001 租户下「查不到」的结果以空串缓存进 Redis hash「1001:sys_config」，
--   且该 hash 无过期时间。部署后必须删掉这一个字段，否则登录用户继续拿到空串：
--     redis-cli -a <密码> HDEL "1001:sys_config" "gz.recycle.notice"
--   （或甲方在 admin 参数设置里打开这条配置点一次保存，保存会刷新缓存。）
--
-- 以后新增 sys_config 行必须显式写 tenant_id='1001'（V202608271157 已写明，本次再犯一次）。
-- 迁移 append-only：不改动 V202609211414（已应用），用本文件订正。
-- ============================================================

UPDATE sys_config
   SET tenant_id = '1001'
 WHERE config_key = 'gz.recycle.notice'
   AND tenant_id = '000000';
