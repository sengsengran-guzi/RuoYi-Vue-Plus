-- ============================================================
-- GZ-RECYCLE-015 ② 点数档「200 点以上」改为占 4 小时（Kevin 2026-08-26 追加）
--
-- 需求原话：「200点以上等于4小时」。
--   原 seed（GZ-RECYCLE-007，V202607082135）给 pts-200-plus 配的是 300 分钟 = 5 格。
--   甲方口径「每 50 点 1 小时」在 200 点封顶：**4 小时是上限**，再多点数也不多占
--   （店里不可能给一个客人占一整天）。
--
-- ⚠️ 连带效果（已向 Kevin 说明并确认）：pts-150-200 本来就是 240 分钟，
--    改完后 **150-200 点与 200 点以上两档占用时长相同（都是 4 格）**。这是刻意的封顶行为，不是配置错误。
--
-- 原 seed 在已提交且各环境已应用的 V202607082135 里，按 append-only 铁律只能新建 UPDATE 迁移。
-- 存量单不受影响：占格面在提交那一刻已冻结进 product_snapshot_json.spanHours（ADR-0022 §4），
-- 改点数档配置不改变既有单的占用宽度。
-- ============================================================

SET NAMES utf8mb4;

UPDATE gz_recycle_qty_range
   SET duration_minutes = 240,
       remark = '每 50 点约 1 小时，200 点封顶 4 小时（可后台改）',
       update_time = NOW()
 WHERE tenant_id = '1001' AND code = 'pts-200-plus' AND del_flag = '0';
